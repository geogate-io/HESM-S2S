#!/bin/bash
set -eo pipefail

# ---------------------------------------------------------------------------
# Build the whole HESM-S2S dependency stack for ONE OpenMPI version, into a
# tree of its own, so several MPI versions can be kept side by side.
#
#   ./build_all_vista.sh                      # builds OMPI_VERSION below
#   OMPI_VERSION=5.0.5  ./build_all_vista.sh
#   OMPI_VERSION=5.0.11 ./build_all_vista.sh
#
# Everything -- packages AND the modulefiles the build scripts generate --
# lands under a single per-MPI root:
#
#   $WORK/envs/openmpi/<OMPI_VERSION>/
#     fms/<ver>  parallelio/<ver>  esmf/<ver>  conduit/<ver>  mpi4py/<ver>
#     modulefiles/{fms,parallelio,esmf-mpi,conduit,mpi4py}/<ver>.lua
#
# To USE a tree built here, replace the `module use` line in
# vista_env_gnu.sh with the matching root, e.g.
#
#   module use -a $WORK/envs/openmpi/5.0.5/modulefiles
#
# NOTE: the older FLAT layout ($WORK/envs/fms/..., built 2026-11-11/12
# against openmpi/5.0.11, reached via `module use -a $WORK/envs/modulefiles`)
# is NOT touched by this script and keeps working exactly as before. Nothing
# here writes outside $INSTALL_ROOT.
#
# Why per-version trees: an Lmod modulefile generated by these scripts
# carries `depends_on("openmpi/<ver>")`, and the libraries under it are built
# against that MPI's headers. One flat tree can therefore only ever describe
# one MPI version -- rebuilding for another silently overwrites it, with no
# way back short of another full rebuild.
# ---------------------------------------------------------------------------

# --- what to build against ------------------------------------------------
OMPI_VERSION=${OMPI_VERSION:-5.0.5}
OMPI=${OMPI:-/opt/apps/gcc14/openmpi/${OMPI_VERSION}}
MODULE_MPI=${MODULE_MPI:-openmpi/${OMPI_VERSION}}
INSTALL_ROOT=${INSTALL_ROOT:-${WORK}/envs/openmpi/${OMPI_VERSION}}

# --- the rest of the toolchain (same for every MPI version) ---------------
MODULE_GCC=${MODULE_GCC:-gcc/14.2.0}
MODULE_CMAKE=${MODULE_CMAKE:-cmake/4.1.1}
MODULE_HDF5=${MODULE_HDF5:-phdf5/1.14.6}
MODULE_NETCDF=${MODULE_NETCDF:-parallelnetcdf/4.9.2}
PYTHON_ENV=${PYTHON_ENV:-${WORK}/envs/hybrid-s2s}
BUILD_DIR_ROOT=${BUILD_DIR_ROOT:-${SCRATCH}/vista_build/openmpi-${OMPI_VERSION}}

# --- package versions (PIO's and mpi4py's are referenced across steps) ----
PIO_VERSION=${PIO_VERSION:-2.6.6}
MPI4PY_VERSION=${MPI4PY_VERSION:-4.1.2}

# --- which steps to run ---------------------------------------------------
# Set any of these to 0 to skip that package, e.g. to re-run just ESMF:
#   BUILD_PIO=0 BUILD_FMS=0 BUILD_MPI4PY=0 BUILD_CONDUIT=0 ./build_all_vista.sh
BUILD_PIO=${BUILD_PIO:-1}
BUILD_FMS=${BUILD_FMS:-1}
BUILD_MPI4PY=${BUILD_MPI4PY:-1}
BUILD_CONDUIT=${BUILD_CONDUIT:-1}
BUILD_ESMF=${BUILD_ESMF:-1}

echo "=============================================================="
echo " OpenMPI      : ${MODULE_MPI}  (${OMPI})"
echo " Install root : ${INSTALL_ROOT}"
echo " Build dir    : ${BUILD_DIR_ROOT}"
echo " Steps        : pio=${BUILD_PIO} fms=${BUILD_FMS} mpi4py=${BUILD_MPI4PY}" \
     "conduit=${BUILD_CONDUIT} esmf=${BUILD_ESMF}"
echo "=============================================================="

if [ ! -d "${OMPI}" ]; then
  echo "ERROR: ${OMPI} does not exist -- check OMPI_VERSION=${OMPI_VERSION}." >&2
  echo "       Available: $(ls -d /opt/apps/gcc14/openmpi/* 2>/dev/null | xargs -n1 basename | tr '\n' ' ')" >&2
  exit 1
fi

module load "${MODULE_GCC}"
module load "${MODULE_MPI}"
module load "${MODULE_CMAKE}"
module load "${MODULE_HDF5}"
module load "${MODULE_NETCDF}"

# The compiler wrappers must come from the SYSTEM module, never from the
# conda env -- conda-forge's own mpicc wrapper invokes a cross-compiler that
# isn't installed here, and its libmpi.so is a different MPI entirely.
for t in mpicc mpicxx mpif90 nc-config nf-config; do
  p=$(command -v $t) || { echo "ERROR: $t not found on PATH" >&2; exit 1; }
  case "$p" in
    ${PYTHON_ENV}/*)
      echo "ERROR: $t resolves to $p -- run 'conda deactivate' first" >&2
      exit 1 ;;
  esac
done

# Confirm the loaded MPI is the one we asked for, not a prerequisite that
# Lmod auto-swapped in while loading something else.
actual_mpicc=$(command -v mpicc)
case "${actual_mpicc}" in
  ${OMPI}/*) : ;;
  *) echo "ERROR: mpicc is ${actual_mpicc}, expected it under ${OMPI}." >&2
     echo "       Something reloaded a different OpenMPI -- check 'module list'." >&2
     exit 1 ;;
esac

mkdir -p "${INSTALL_ROOT}"

# PIO
if [ "${BUILD_PIO}" = 1 ]; then
echo "### ParallelIO ###"
INSTALL_ROOT=${INSTALL_ROOT} \
BUILD_DIR_ROOT=${BUILD_DIR_ROOT} \
PLATFORM_LABEL=Vista \
PIO_RELEASE_VERSION=${PIO_VERSION} \
MODULE_NCARENV="" \
MODULE_GCC="${MODULE_GCC}" \
MODULE_HDF5="${MODULE_HDF5}" \
MODULE_CMAKE="${MODULE_CMAKE}" \
MODULE_MPI="${MODULE_MPI}" \
MODULE_NETCDF="${MODULE_NETCDF}" \
./HESM-S2S/envs/build_parallelio.sh
fi

# FMS
if [ "${BUILD_FMS}" = 1 ]; then
echo "### FMS ###"
INSTALL_ROOT=${INSTALL_ROOT} \
BUILD_DIR_ROOT=${BUILD_DIR_ROOT} \
PLATFORM_LABEL=Vista \
MODULE_NCARENV="" \
MODULE_GCC="${MODULE_GCC}" \
MODULE_HDF5="${MODULE_HDF5}" \
MODULE_CMAKE="${MODULE_CMAKE}" \
MODULE_MPI="${MODULE_MPI}" \
MODULE_NETCDF="${MODULE_NETCDF}" \
./HESM-S2S/envs/build_fms.sh
fi

# MPI4py
if [ "${BUILD_MPI4PY}" = 1 ]; then
echo "### mpi4py ###"
LDSHARED="$OMPI/bin/mpicc -shared -Wl,-rpath,$OMPI/lib" \
MPI4PY_VERSION=${MPI4PY_VERSION} \
INSTALL_ROOT=${INSTALL_ROOT} \
BUILD_DIR_ROOT=${BUILD_DIR_ROOT} \
PLATFORM_LABEL=Vista \
MODULE_NCARENV="" \
MODULE_GCC="${MODULE_GCC}" \
MODULE_MPI="${MODULE_MPI}" \
MPICC_WRAPPER=$OMPI/bin/mpicc \
PYTHON_ENV=${PYTHON_ENV} \
./HESM-S2S/envs/build_mpi4py.sh
fi

# CONDUIT
if [ "${BUILD_CONDUIT}" = 1 ]; then
echo "### conduit ###"
INSTALL_ROOT=${INSTALL_ROOT} \
BUILD_DIR_ROOT=${BUILD_DIR_ROOT} \
PLATFORM_LABEL=Vista \
OMPI=${OMPI} \
MODULE_NCARENV="" \
MODULE_GCC="${MODULE_GCC}" \
MODULE_MPI="${MODULE_MPI}" \
MODULE_CMAKE="${MODULE_CMAKE}" \
MPICC_WRAPPER=$OMPI/bin/mpicc \
MPICXX_WRAPPER=$OMPI/bin/mpicxx \
MPIF90_WRAPPER=$OMPI/bin/mpif90 \
PYTHON_ENV=${PYTHON_ENV} \
./HESM-S2S/envs/build_conduit.sh
fi

# ESMF -- needs the ParallelIO built just above, so point MODULEPATH at
# THIS tree's modulefiles (not $WORK/envs/modulefiles, which is the old
# flat 5.0.11 layout and would link ESMF against the wrong PIO).
if [ "${BUILD_ESMF}" = 1 ]; then
echo "### ESMF ###"
module use -a ${INSTALL_ROOT}/modulefiles
module load parallelio/${PIO_VERSION}

INSTALL_ROOT=${INSTALL_ROOT} \
BUILD_DIR_ROOT=${BUILD_DIR_ROOT} \
PLATFORM_LABEL=Vista \
OMPI=${OMPI} \
ESMF_F90LINKLIBS="-lm" \
PIO_C_INCLUDE_DIR=${INSTALL_ROOT}/parallelio/${PIO_VERSION}/include \
PIO_C_LIBRARY=${INSTALL_ROOT}/parallelio/${PIO_VERSION}/lib \
MODULE_NCARENV=TACC \
MODULE_GCC="${MODULE_GCC}" \
MODULE_MPI="${MODULE_MPI}" \
MODULE_CMAKE="${MODULE_CMAKE}" \
MODULE_HDF5="${MODULE_HDF5}" \
MODULE_NETCDF="${MODULE_NETCDF}" \
MODULE_PIO="parallelio/${PIO_VERSION}" \
./HESM-S2S/envs/build_esmf.sh
fi

echo
echo "=============================================================="
echo " Done. Built against ${MODULE_MPI} under:"
echo "   ${INSTALL_ROOT}"
echo
echo " To use this tree, put this in vista_env_gnu.sh IN PLACE OF the"
echo " existing 'module use -a .../modulefiles' line:"
echo
echo "   module use -a ${INSTALL_ROOT}/modulefiles"
echo "   module load fms/..."
echo "   module load parallelio/${PIO_VERSION}"
echo "   module load esmf-mpi/..."
echo "   module load conduit/..."
echo "   module load mpi4py/${MPI4PY_VERSION}"
echo
echo " and make sure the OpenMPI line above them reads:"
echo "   module load ${MODULE_MPI}"
echo
echo " Installed module versions:"
for d in "${INSTALL_ROOT}"/modulefiles/*/; do
  [ -d "$d" ] || continue
  printf '   %-14s %s\n' "$(basename "$d")" \
    "$(ls "$d" 2>/dev/null | sed 's/\.lua$//' | tr '\n' ' ')"
done
echo "=============================================================="
